"""Numerical filter validation: measured gain (dB) of each filter type/method at passband and stopband test tones.

    cd backend && python ../scripts/filter_validation.py --markdown ../docs/filter_validation_report.md

Method: unit-amplitude-ish sine tones (one per frequency, 0.2 amplitude, 4 s) are passed through run_filter(); gain is measured on the
central 50 % of the output (edge transients excluded) as the Goertzel-style single-bin amplitude ratio. Pass criteria derive from the
design: passband tones within 0.5 dB (zero-phase: 1.0 dB near the band edge is not tested), stopband tones at least `min_atten_db` down,
where min_atten_db is the theoretical |H|(f) of that design minus 3 dB slack (so the test follows the design, not a guess).
"""
import argparse, sys, os
import numpy as np
sys.path[:0] = [os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "backend")]
from app.processing import filters as flt

def gain_db(x, y):
    n = x.size; a, b = n // 4, 3 * n // 4
    xs, ys = x[a:b], y[a:b]
    return 20 * np.log10(max(np.sqrt(np.mean(ys ** 2)), 1e-300) / np.sqrt(np.mean(xs ** 2)))

CASES = [("lowpass", [1000.0], [200, 500], [3000, 5000]), ("highpass", [1000.0], [3000, 5000], [100, 300]),
         ("bandpass", [800.0, 2000.0], [1200, 1500], [100, 4000]), ("bandstop", [800.0, 2000.0], [100, 4000], [1200, 1500])]
def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--markdown"); a = ap.parse_args()
    rows, fails = [], 0
    for fs in (8000, 16000, 44100, 48000):
        t = np.arange(int(4 * fs)) / fs
        for method in ("causal", "zero_phase"):
            for typ, cut, passf, stopf in CASES:
                for order in (2, 6):
                    sos = flt.design_filter(typ, order, cut, fs)
                    for role, freqs in (("pass", passf), ("stop", stopf)):
                        for f in freqs:
                            if f >= fs / 2: continue
                            x = 0.2 * np.sin(2 * np.pi * f * t)
                            y = flt.run_filter(x, fs, typ, order, cut, method)["output"][0]
                            g = gain_db(x, y)
                            w, h = __import__("scipy.signal", fromlist=["sosfreqz"]).sosfreqz(sos, worN=[f], fs=fs)
                            theo = 20 * np.log10(abs(h[0]) + 1e-300) * (2 if method == "zero_phase" else 1)
                            ok = (abs(g) <= 0.5) if role == "pass" else (g <= max(theo + 3.0, -300) or g < -100)
                            if role == "pass" and abs(theo) > 0.4: ok = abs(g - theo) <= 1.0   # near an edge: must match the design
                            fails += (not ok)
                            rows.append((fs, method, typ, order, f, role, g, theo, ok))
    print(f"{len(rows)} checks, {fails} failures")
    if a.markdown:
        with open(a.markdown, "w") as fh:
            fh.write("# Numerical filter validation (generated by scripts/filter_validation.py)\n\n")
            fh.write(f"Measured on this machine (NumPy {np.__version__}). {len(rows)} tone checks, **{fails} failures**. Gain = RMS(out)/RMS(in) on the central 50 % of a 4 s tone; "
                     "`design dB` = |H(f)| of the designed SOS (x2 in dB for zero-phase). A check passes if passband gain is within 0.5 dB of 0 (or within 1 dB of the design near an edge) "
                     "and stopband gain is at most the design value + 3 dB.\n\n| fs | method | type | order | tone Hz | role | measured dB | design dB | pass |\n|---|---|---|---|---|---|---|---|---|\n")
            for fs, m, ty, o, f, r, g, th, ok in rows:
                fh.write(f"| {fs} | {m} | {ty} | {o} | {f} | {r} | {g:.2f} | {th:.2f} | {'yes' if ok else '**NO**'} |\n")
    sys.exit(1 if fails else 0)
main()
